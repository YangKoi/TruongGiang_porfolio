let currentLang = localStorage.getItem("portfolio_lang") || "vi";

function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("portfolio_lang", lang);
    const t = i18n[lang];

    // Document title
    document.title = `${t.profile.name} | Portfolio`;

    // Update lang toggle button
    const langBtn = document.getElementById("lang-toggle");
    if (langBtn) {
        langBtn.textContent = lang === "vi" ? "EN" : "VI";
        langBtn.setAttribute("title", lang === "vi" ? "Switch to English" : "Chuyển sang Tiếng Việt");
    }

    // NAV links
    const navMap = ["about", "skills", "experience", "projects", "contact"];
    navMap.forEach(id => {
        const link = document.querySelector(`.nav-link[href="#${id}"]`);
        if (link) link.textContent = t.nav[id];
    });

    // PROFILE SECTION
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const keys = key.split(".");
        let value = t;
        for (const k of keys) value = value?.[k];
        if (value !== undefined) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = value;
            } else if (el.hasAttribute("data-i18n-html")) {
                el.innerHTML = value;
            } else {
                el.textContent = value;
            }
        }
    });

    // MODAL loading text — update if visible
    const modalLoading = document.querySelector(".modal-loading");
    if (modalLoading) modalLoading.textContent = t.modal.loading;
}

function toggleLanguage() {
    applyLanguage(currentLang === "vi" ? "en" : "vi");
}


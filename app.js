    // 6. Carousel Logic
    function initCarousel() {
        carouselSlides = document.querySelectorAll(".carousel-slide");
        carouselDots = document.querySelectorAll(".carousel-dot");
        const prevBtn = document.querySelector(".carousel-prev");
        const nextBtn = document.querySelector(".carousel-next");

        if (carouselSlides.length <= 1) {
            if (prevBtn) prevBtn.style.display = "none";
            if (nextBtn) nextBtn.style.display = "none";
            return;
        }

        prevBtn.addEventListener("click", showPrevSlide);
        nextBtn.addEventListener("click", showNextSlide);
        carouselDots.forEach(dot => {
            dot.addEventListener("click", () => goToSlide(parseInt(dot.getAttribute("data-index"))));
        });
    }

    function goToSlide(index) {
        if (index >= carouselSlides.length) activeCarouselIndex = 0;
        else if (index < 0) activeCarouselIndex = carouselSlides.length - 1;
        else activeCarouselIndex = index;

        carouselSlides.forEach((slide, i) => slide.classList.toggle("active", i === activeCarouselIndex));
        carouselDots.forEach((dot, i) => dot.classList.toggle("active", i === activeCarouselIndex));
    }

    function showNextSlide() { goToSlide(activeCarouselIndex + 1); }
    function showPrevSlide() { goToSlide(activeCarouselIndex - 1); }

